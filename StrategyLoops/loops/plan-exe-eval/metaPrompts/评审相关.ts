export function Commit(): string {
  return ` 
  提交次数：一次或多次提交
  提交步骤：将git暂存区代码和svn（或项目指定使用的其它资产仓库）变更做一次深度理解。一步步来，慢思考，如果工作区存在暂存区的依赖，将工作区中的文件添加到暂存，不依赖则不添加。
  先检查忽略文件（gitignore和.svnignore）是否合理覆盖，标准：见下方代码仓库和资产仓库职责划分。然后进行一次commit。
  根据该项目的要求，编写详实、合规的提交信息。
  提交模版 标签(模块或文件夹)(子模块或文件或特定行为): 中文内容。
  如:
  explore_in_progress(UI)(交互):探索新交互布局...(具体探索)
  feat(input)(跨平台):输入新增跨平台特性...(具体特性)
  detail(产品Icon)(样式):给产品Icon添加新样式...(具体细节)
  add(埋点)(统计):新增埋点模块...(具体实现)

  要写具体一点！

  以下所称”代码仓库“指项目中使用的主力存放代码、文档、文本和小微资产的仓库。
  “资产仓库”指项目中专门存放大文件的仓库。

  [大文件检查] 代码仓库当中不应当包含任何大文件（超过3mb 的图片、音视频、动画、数据库文件、二进制文件、各种资产），请务必检查并ignore
  [资产仓库] 根据项目所使用的资产仓库(通常是SVN、Git LFS等，以项目历史约定为准)
  [仓库职责分离]确保大文件在资产仓库的跟踪中；确保代码、文档等文本文件不处于资产仓库中，只处于代码仓库中（有一些动态性较强的小型资产比如icon、小音频、场景描述文件、预制体等可以被赦免，放进代码仓库，这取决于项目决策，请查看项目文档遵循历史约定）。
  [仓库依赖链] 代码仓库可以依赖资产仓库中的文件，但资产仓库不应当依赖代码仓库中的文件。（永远记住，依赖链的上游：代码仓库；依赖链的下游：资产仓库）
  [资产仓库稀疏提交] 由于大文件提交非常占据空间，必须遵循"稀疏提交原则"，不要频繁提交资产仓库。判断该次代码代码仓库的变更或提交是否涉及对资产的使用、引用变更，如果没有，资产仓库不提交（资产仓库工作区堆积没关系）；如果有，资产仓库应随代码仓库进行一次提交。

  标签应该从以下列表中选择：
  "detail",
  "add",
  "feat",
  "fix",
  "refactor",
  "BIG_CHANGE",
  "chore",
  "adjust",
  "revert",
  "test",
  "explore_in_progress",
  "merge",
  "milestone"`
}

